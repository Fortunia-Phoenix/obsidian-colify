var EXTRA_BLANK_LINE_MARKER_SELECTOR = ".colify-extra-blank-line-marker";
var LIST_ITEM_PATTERN = /^ {0,3}(?:[-+*]|\d{1,9}[.)])(?:[ \t]+|$)/;
var BLOCKQUOTE_PATTERN = /^ {0,3}>/;
var INDENTED_CODE_PATTERN = /^(?: {4}|\t)/;
var TABLE_ROW_PATTERN = /^\s*\|?.+\|.+\|?\s*$/;
var BLOCK_SEPARATOR_PATTERN = /^ {0,3}(?:[-*_]\s*){3,}$/;
function prepareMarkdownRenderSource(content) {
  const markdown = ensureTableBlockBoundaries(normalizeLineEndings(content));
  const lines = ensureImageCommentBlockBoundaries(markdown.split("\n"));
  const protectedLines = findProtectedMarkdownLines(lines);
  const output = [];
  for (let index = 0; index < lines.length; ) {
    if (lines[index].trim().length > 0) {
      output.push(lines[index]);
      index++;
      continue;
    }
    const blankStart = index;
    while (index < lines.length && lines[index].trim().length === 0) {
      index++;
    }
    const blankCount = index - blankStart;
    if (blankCount > 1 && canPreserveExtraBlankLines(
      lines,
      protectedLines,
      blankStart,
      index
    )) {
      output.push(
        "",
        createExtraBlankLineMarker(blankCount - 1),
        ""
      );
      continue;
    }
    for (let blankIndex = 0; blankIndex < blankCount; blankIndex++) {
      output.push("");
    }
  }
  return output.join("\n");
}
function ensureImageCommentBlockBoundaries(lines) {
  const output = [];
  for (const line of lines) {
    if (isColifyImageCommentLine(line) && output.length > 0 && output[output.length - 1].trim().length > 0) {
      output.push("");
    }
    output.push(line);
  }
  return output;
}
function createExtraBlankLineMarker(count) {
  return `<span class="colify-extra-blank-line-marker" data-colify-extra-blank-lines="${count}" aria-hidden="true"></span>`;
}
function canPreserveExtraBlankLines(lines, protectedLines, blankStart, nextLine) {
  if (blankStart === 0 || nextLine >= lines.length) {
    return false;
  }
  if (protectedLines[blankStart - 1] || protectedLines[nextLine]) {
    return false;
  }
  return !isSensitiveAdjacentBlock(lines, blankStart - 1, -1) && !isSensitiveAdjacentBlock(lines, nextLine, 1);
}
function isSensitiveAdjacentBlock(lines, start, direction) {
  for (let index = start; index >= 0 && index < lines.length && lines[index].trim().length > 0; index += direction) {
    if (isBlockSensitiveLine(lines[index])) {
      return true;
    }
  }
  return false;
}
function isBlockSensitiveLine(line) {
  return LIST_ITEM_PATTERN.test(line) || BLOCKQUOTE_PATTERN.test(line) || INDENTED_CODE_PATTERN.test(line) || TABLE_ROW_PATTERN.test(line) || BLOCK_SEPARATOR_PATTERN.test(line);
}

// src/markdownEditableBlocks.ts
var ATX_HEADING_PATTERN = /^ {0,3}#{1,6}(?:\s+|$)/;
var BLOCK_QUOTE_PATTERN = /^ {0,3}>/;
var LIST_ITEM_PATTERN2 = /^ {0,3}(?:[-+*]|\d+[.)])\s+/;
var SETEXT_HEADING_PATTERN = /^ {0,3}(?:=+|-+)\s*$/;
var MATH_FENCE_PATTERN = /^ {0,3}\$\$\s*$/;
function parseMarkdownEditableBlocks(markdown) {
  if (markdown.length === 0) {
    return [createBlock(markdown, 0, 0, "empty", true)];
  }
  const lines = splitSourceLines(markdown);
  const blocks = [];
  let lineIndex = 0;
  while (lineIndex < lines.length) {
    if (isBlankLine(lines[lineIndex].text)) {
      lineIndex++;
      continue;
    }
    const startIndex = lineIndex;
    const fence = getFenceStart(lines[lineIndex].text);
    if (fence) {
      lineIndex = consumeFence(lines, lineIndex, fence);
      blocks.push(
        createBlockFromLines(markdown, lines, startIndex, lineIndex, "code", true)
      );
      continue;
    }
    if (MATH_FENCE_PATTERN.test(lines[lineIndex].text)) {
      lineIndex = consumeMathFence(lines, lineIndex);
      blocks.push(
        createBlockFromLines(markdown, lines, startIndex, lineIndex, "math", true)
      );
      continue;
    }
    if (isTableStart(lines, lineIndex)) {
      lineIndex = consumeTable(lines, lineIndex);
      blocks.push(
        createBlockFromLines(markdown, lines, startIndex, lineIndex, "table", false)
      );
      continue;
    }
    if (BLOCK_QUOTE_PATTERN.test(lines[lineIndex].text)) {
      lineIndex = consumeQuote(lines, lineIndex);
      blocks.push(
        createBlockFromLines(markdown, lines, startIndex, lineIndex, "quote", true)
      );
      continue;
    }
    if (LIST_ITEM_PATTERN2.test(lines[lineIndex].text)) {
      lineIndex = consumeList(lines, lineIndex);
      blocks.push(
        createBlockFromLines(markdown, lines, startIndex, lineIndex, "list", true)
      );
      continue;
    }
    if (ATX_HEADING_PATTERN.test(lines[lineIndex].text)) {
      lineIndex++;
      blocks.push(
        createBlockFromLines(
          markdown,
          lines,
          startIndex,
          lineIndex,
          "heading",
          true
        )
      );
      continue;
    }
    if (lineIndex + 1 < lines.length && SETEXT_HEADING_PATTERN.test(lines[lineIndex + 1].text)) {
      lineIndex += 2;
      blocks.push(
        createBlockFromLines(
          markdown,
          lines,
          startIndex,
          lineIndex,
          "heading",
          true
        )
      );
      continue;
    }
    lineIndex = consumeParagraph(lines, lineIndex);
    blocks.push(
      createBlockFromLines(
        markdown,
        lines,
        startIndex,
        lineIndex,
        "paragraph",
        true
      )
    );
  }
  return blocks.length > 0 ? blocks : [createBlock(markdown, 0, 0, "empty", true)];
}
function replaceMarkdownEditableBlock(markdown, block, replacement) {
  const from = clampOffset(block.from, markdown.length);
  const to = Math.max(from, clampOffset(block.to, markdown.length));
  return `${markdown.slice(0, from)}${replacement}${markdown.slice(to)}`;
}
function splitSourceLines(markdown) {
  const lines = [];
  let start = 0;
  while (start <= markdown.length) {
    const newlineIndex = markdown.indexOf("\n", start);
    const fullEnd = newlineIndex === -1 ? markdown.length : newlineIndex + 1;
    let end = newlineIndex === -1 ? markdown.length : newlineIndex;
    if (end > start && markdown.charCodeAt(end - 1) === 13) {
      end--;
    }
    lines.push({
      end,
      fullEnd,
      start,
      text: markdown.slice(start, end)
    });
    if (newlineIndex === -1) {
      break;
    }
    start = fullEnd;
  }
  return lines;
}
function consumeFence(lines, startIndex, fence) {
  let lineIndex = startIndex + 1;
  while (lineIndex < lines.length) {
    if (isFenceEnd(lines[lineIndex].text, fence)) {
      return lineIndex + 1;
    }
    lineIndex++;
  }
  return lineIndex;
}
function consumeMathFence(lines, startIndex) {
  let lineIndex = startIndex + 1;
  while (lineIndex < lines.length) {
    if (MATH_FENCE_PATTERN.test(lines[lineIndex].text)) {
      return lineIndex + 1;
    }
    lineIndex++;
  }
  return lineIndex;
}
function consumeQuote(lines, startIndex) {
  let lineIndex = startIndex + 1;
  while (lineIndex < lines.length) {
    if (BLOCK_QUOTE_PATTERN.test(lines[lineIndex].text)) {
      lineIndex++;
      continue;
    }
    if (isBlankLine(lines[lineIndex].text) && lineIndex + 1 < lines.length && BLOCK_QUOTE_PATTERN.test(lines[lineIndex + 1].text)) {
      lineIndex++;
      continue;
    }
    break;
  }
  return lineIndex;
}
function consumeList(lines, startIndex) {
  let lineIndex = startIndex + 1;
  while (lineIndex < lines.length) {
    const line = lines[lineIndex].text;
    if (isBlankLine(line)) {
      const nextContentIndex = findNextContentLine(lines, lineIndex + 1);
      if (nextContentIndex < lines.length && (isIndentedListContinuation(lines[nextContentIndex].text) || LIST_ITEM_PATTERN2.test(lines[nextContentIndex].text))) {
        lineIndex++;
        continue;
      }
      break;
    }
    if (LIST_ITEM_PATTERN2.test(line) || isIndentedListContinuation(line)) {
      lineIndex++;
      continue;
    }
    if (startsStandaloneBlock(lines, lineIndex)) {
      break;
    }
    lineIndex++;
  }
  return lineIndex;
}
function consumeTable(lines, startIndex) {
  let lineIndex = startIndex + 2;
  while (lineIndex < lines.length && !isBlankLine(lines[lineIndex].text) && lines[lineIndex].text.includes("|")) {
    lineIndex++;
  }
  return lineIndex;
}
function consumeParagraph(lines, startIndex) {
  let lineIndex = startIndex + 1;
  while (lineIndex < lines.length) {
    if (isBlankLine(lines[lineIndex].text)) {
      break;
    }
    if (startsStandaloneBlock(lines, lineIndex)) {
      break;
    }
    lineIndex++;
  }
  return lineIndex;
}
function startsStandaloneBlock(lines, lineIndex) {
  const line = lines[lineIndex].text;
  return Boolean(
    getFenceStart(line) || MATH_FENCE_PATTERN.test(line) || ATX_HEADING_PATTERN.test(line) || BLOCK_QUOTE_PATTERN.test(line) || LIST_ITEM_PATTERN2.test(line) || isTableStart(lines, lineIndex)
  );
}
function isTableStart(lines, lineIndex) {
  return lineIndex + 1 < lines.length && lines[lineIndex].text.includes("|") && isTableDelimiter(lines[lineIndex + 1].text);
}
function isTableDelimiter(line) {
  const trimmed = line.trim();
  if (!trimmed.includes("|")) {
    return false;
  }
  const cells = trimmed.replace(/^\|/, "").replace(/\|$/, "").split("|").map((cell) => cell.trim());
  return cells.length > 0 && cells.every((cell) => /^:?-{3,}:?$/.test(cell));
}
function getFenceStart(line) {
  const match = /^ {0,3}(`{3,}|~{3,})/.exec(line);
  if (!match) {
    return null;
  }
  return {
    character: match[1][0],
    length: match[1].length
  };
}
function isFenceEnd(line, fence) {
  const trimmed = line.trimStart();
  let length = 0;
  while (trimmed[length] === fence.character) {
    length++;
  }
  return length >= fence.length && trimmed.slice(length).trim().length === 0;
}
function isIndentedListContinuation(line) {
  return /^(?: {2,}|\t)\S/.test(line);
}
function findNextContentLine(lines, startIndex) {
  let lineIndex = startIndex;
  while (lineIndex < lines.length && isBlankLine(lines[lineIndex].text)) {
    lineIndex++;
  }
  return lineIndex;
}
function createBlockFromLines(markdown, lines, startIndex, endIndex, kind, editable) {
  const from = lines[startIndex].start;
  const to = lines[Math.max(startIndex, endIndex - 1)].end;
  return createBlock(markdown, from, to, kind, editable);
}
function createBlock(markdown, from, to, kind, editable) {
  return {
    content: markdown.slice(from, to),
    editable,
    from,
    kind,
    to
  };
}
function isBlankLine(line) {
  return line.trim().length === 0;
}
function clampOffset(offset, length) {
  if (!Number.isFinite(offset)) {
    return 0;
  }
  return Math.min(length, Math.max(0, Math.trunc(offset)));
}

